//! 导入：把外面的照片按模版搬进库里（`REPOSITORY.md` §3–§4）。
//!
//! 模块划分（每一块都能单独测）：
//!
//! | 模块 | 职责 |
//! | --- | --- |
//! | [`template`] | 模版的解析 / 校验 / 渲染（纯函数，不认识磁盘与数据库） |
//! | `plan` | 目标路径规划：目录透传、位图/RAW 分流、重名后缀、序号分配（可注入 FS） |
//! | [`fsops`] | 真实文件操作 + 内存假实现（测试用） |
//! | [`progress`] | 进度快照（阶段、计数、当前项、错误） |
//! | [`runner`] | 后台执行：阶段机、暂停/取消、逐文件复制与登记 |
//!
//! **本模块不依赖 Tauri**（`AGENTS.md` §2.4/§4）：文件系统之外的东西（`app.db` 的任务队列、
//! 往界面推进度）都通过注入的回调/接口拿进来，由 `src-tauri` 提供实现。

pub mod fsops;
pub mod progress;
pub mod runner;
pub mod plan;
pub mod template;
