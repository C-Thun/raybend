/**
 * `ToolsSeparator` —— toolsbar 上的**组分隔符**（崔总 2026-09-28 定）。
 *
 * 一条浅浅的竖线，两侧各留一点间距。它只做一件事：**把相邻的组分开**，
 * 让「这一排控件是几件事」一眼可读 —— 组内几乎无间距，组间才有它。
 *
 * ```text
 * [删除] │ [撤销][重做] │ [筛选] │ [旗标][清旗] │ [★★★★★] │ [●●●●●●] │ [👍👎] │ [标签] │ [锁]
 *        └── 都是它 ──┘
 * ```
 *
 * ## 分组规则（唯一事实来源在 `memory/DESIGN.md` §12.12，这里是摘要）
 *
 * 1. **语义不同的动作换组**：可逆（撤销/重做）与不可逆（删除）之间**必须**有 ——
 *    「这两个长得像的按钮做的事不一样」要看得出来；
 * 2. **控件形态换组**：按钮组、开关（`ToggleBlock`）、标记排（星/色/赞踩）之间；
 * 3. **一个独立控件也算一组**：它两侧照样有分隔；
 * 4. 组**内**不用它 —— 组内间距收到几乎为零（`gap-0.5`），靠控件自己的内边距分开。
 *
 * ## 不用的地方
 *
 * * toolsbar 的 left / right 段与 mid 之间 —— 那是三段式布局的事，不是分组；
 * * 弹窗、面板内部的分隔 —— 那里用留白或 `surface` 台阶，不需要线。
 */

/** 组间分隔：1px 竖线 + 两侧各 4px。无内容、无语义，读屏忽略。 */
export function ToolsSeparator() {
  return (
    <span
      data-tools-separator
      aria-hidden="true"
      class="mx-1 h-4 w-px shrink-0 self-center bg-line-2"
    />
  );
}
